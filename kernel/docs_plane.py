# ---------------------------------------------------------------- parsing

def parse(path):
    """{id, title, path, fields}: the H1 and every `## Field` section (first occurrence wins)."""
    lines = path.read_text(encoding="utf-8").splitlines()
    first = next((line for line in lines if line.startswith("# ")), "")
    match = H1.match(first)
    fields, current, buffer = {}, None, []

    def flush():
        if current is not None and current not in fields:
            fields[current] = "\n".join(buffer).strip()

    for line in lines:
        heading = FIELD.match(line)
        if heading or line.startswith("# "):
            flush()
            current, buffer = (heading.group(1) if heading else None), []
        elif current is not None:
            buffer.append(line)
    flush()
    return {"id": match.group(1) if match else None, "title": match.group(2) if match else None,
            "path": path, "fields": fields}


def value(item, field):
    """The field's first paragraph on one line."""
    text = item["fields"].get(field, "")
    return " ".join(text.split("\n\n")[0].split())


def items(kind, root=ROOT):
    folder = root / KINDS[kind]["folder"]
    return [parse(p) for p in sorted(folder.glob("*.md")) if not p.name.startswith("_")]


def _sort_key(identifier):
    match = re.match(r"([A-Z]+)-?([A-Z]*)(\d+)", identifier)
    series = {"Q": 0, "A": 1, "B": 2, "F": 3, "O": 4}.get(match.group(2), 5) if match and match.group(2) else 0
    return (match.group(1) if match else identifier, series, int(match.group(3)) if match else 0)


def _rel(path, start):
    return Path(os.path.relpath(path, start)).as_posix()


def _cell(text, limit=None):
    text = " ".join(str(text).split()).replace("|", "\\|")
    return text if limit is None or len(text) <= limit else text[:limit - 1].rstrip() + "…"


def _table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
                     + ["| " + " | ".join(row) + " |" for row in rows])


