def problems(root=ROOT):
    found = []
    every = {kind: items(kind, root) for kind in KINDS}
    ids = {}
    for kind, spec in KINDS.items():
        if not (root / spec["folder"] / "_template.md").exists():
            found.append(f"{spec['folder']}/_template.md is missing")
        for item in every[kind]:
            name = item["path"].relative_to(root).as_posix()
            if not item["id"] or not re.fullmatch(spec["id"], item["id"]):
                found.append(f"{name}: the first line must be '# <{spec['id']}> — <Title>'")
                continue
            if kind != "plans" and not item["path"].stem.startswith(item["id"] + "-"):
                found.append(f"{name}: the file name must start with its ID {item['id']}")
            if item["id"] in ids:
                found.append(f"{name}: ID {item['id']} is also used by {ids[item['id']]}")
            ids[item["id"]] = name
            for field, allowed in spec["fields"].items():
                text = value(item, field)
                if not text:
                    found.append(f"{name}: field '{field}' is empty or missing")
                elif isinstance(allowed, tuple) and text not in allowed:
                    found.append(f"{name}: {field} '{text}' is not one of {', '.join(allowed)}")
                elif isinstance(allowed, re.Pattern) and not allowed.match(text):
                    found.append(f"{name}: {field} '{text}' is not a date (YYYY-MM-DD)")
    found += _link_problems(root)
    found += _decision_problems(every["decisions"])
    found += _rule_problems(root, every["decisions"])
    found += _backlog_problems(root, every)
    found += _finding_problems(every["findings"])
    found += _session_problems(every["sessions"])
    found += _freeze_problems(root)
    found += _schema_problems(root)
    from kernel.build_docs import step_modules  # noqa: F401  (layer labels cover every node)

    order = yaml.safe_load((root / "kernel" / "layer_order.yaml").read_text(encoding="utf-8"))
    if {n["id"] for n in order["nodes"]} != set(LAYER_LABELS):
        found.append("kernel/docs_plane.LAYER_LABELS does not name exactly the nodes of kernel/layer_order.yaml")
    for path, text in generated(root).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            found.append(f"{path.relative_to(root)} is stale (run python -m kernel.docs_plane --write)")
    return found


def _link_problems(root):
    found = []
    files = [root / "AGENTS.md", root / "CHANGELOG.md", *sorted((root / "docs").rglob("*.md"))]
    for path in files:
        if not path.exists() or "reference" in path.relative_to(root).parts or "sources" in path.relative_to(root).parts:
            continue
        text = path.read_text(encoding="utf-8")
        text = re.sub(r"```.*?```", "", text, flags=re.S)
        for target in LINK.findall(text):
            if "<" in target or target.startswith("{"):
                continue
            if not (path.parent / target).resolve().exists():
                found.append(f"{path.relative_to(root)}: link to missing file {target}")
    return found


def _decision_problems(decisions):
    found, by_id = [], {d["id"]: d for d in decisions}
    for d in decisions:
        for field, other_field in (("Supersedes", "Superseded By"), ("Superseded By", "Supersedes")):
            for target in re.findall(r"ADR-[A-Z]\d+", value(d, field)):
                if target not in by_id:
                    found.append(f"{d['id']}: {field} names {target}, which has no file")
                elif d["id"] not in value(by_id[target], other_field):
                    found.append(f"{d['id']}: {field} {target}, but {target} does not say {other_field} {d['id']}")
        if value(d, "Status") == "superseded" and not re.search(r"ADR-", value(d, "Superseded By")):
            found.append(f"{d['id']}: superseded, but Superseded By names no ADR")
    return found


def _rule_problems(root, decisions):
    found, status = [], {d["id"]: value(d, "Status") for d in decisions}
    data = rules_data(root)
    seen = set()
    for rule in data["rules"]:
        if rule["id"] in seen:
            found.append(f"docs/rules.yaml: {rule['id']} appears twice")
        seen.add(rule["id"])
        for source in rule["source"]:
            if status.get(source) != "accepted":
                found.append(f"docs/rules.yaml: {rule['id']} cites {source}, which is {status.get(source, 'missing')}")
    return found


def _backlog_problems(root, every):
    found, data, codes = [], backlog(root), repo_codes(root)
    ids = {i["id"] for i in data["items"]}
    plans = {p["id"] for p in every["plans"]}
    findings = {f["id"] for f in every["findings"]}
    for item in data["items"]:
        new = item.get("codes", [])
        if item["status"] not in BACKLOG_STATUS:
            found.append(f"backlog {item['id']}: status {item['status']} is unknown")
        if item["status"] == "done" and any(c not in codes for c in new):
            found.append(f"backlog {item['id']}: done, but {[c for c in new if c not in codes]} are not in the code")
        if item["status"] != "done" and new and all(c in codes for c in new):
            found.append(f"backlog {item['id']}: every new code is in the code; mark it done or name what is missing")
        if item["step"] not in LAYER_LABELS and item["step"] not in ("all", "docs", "owner"):
            found.append(f"backlog {item['id']}: step {item['step']} is not a layer_order node, all, docs or owner")
        for dep in item.get("depends_on", []):
            if dep not in ids:
                found.append(f"backlog {item['id']}: depends on unknown {dep}")
        for finding in item.get("findings", []):
            if finding not in findings:
                found.append(f"backlog {item['id']}: names unknown finding {finding}")
        if item.get("plan") not in plans:
            found.append(f"backlog {item['id']}: plan {item.get('plan')} has no file")
    return found


SELF_AUDIT_FROM = 55  # RV-45 (F-128, F-166): from S-055 an applied session records its self-audit (R-03, R-31)


def _session_problems(sessions):
    """RV-45: an applied or reverted session from S-055 on has a Self-audit section with content (R-03, R-31)."""
    return [f"{s['path'].name}: an applied session from S-{SELF_AUDIT_FROM:03d} records its self-audit (R-03, R-31)"
            for s in sessions if int(s["id"][2:]) >= SELF_AUDIT_FROM and value(s, "Status") in ("applied", "reverted")
            and not value(s, "Self-audit")]


def _finding_problems(findings):
    """F1-F15 (the renders report): resolved exactly when the checklist names a code that catches it."""
    from validators.checklist import FINDINGS

    found = []
    for f in findings:
        legacy = value(f, "Legacy ID")
        if legacy in FINDINGS and value(f, "Status") != "duplicate":
            caught = bool(FINDINGS[legacy][2])
            if caught != (value(f, "Status") == "resolved"):
                found.append(f"{f['id']} ({legacy}): status {value(f, 'Status')} but the checklist's caught_by is "
                             f"{list(FINDINGS[legacy][2]) or 'empty'}")
    return found


def _schema_problems(root):
    """docs/rules.yaml and kernel/layer_order.yaml against their schemas (owner O65); the shared definitions' copies."""
    import json

    from kernel.canonical import ContractError
    from kernel.shared_schemas import problems as shared_problems
    from validators.schema_validator import validate_schema

    found = []
    for data, schema in (("docs/rules.yaml", "schemas/rules.schema.json"),
                         ("kernel/layer_order.yaml", "schemas/layer_order.schema.json")):
        try:
            validate_schema(yaml.safe_load((root / data).read_text(encoding="utf-8")),
                            json.loads((root / schema).read_text(encoding="utf-8")))
        except ContractError as error:
            found.append(f"{data} does not match {schema}: {error}")
    return found + shared_problems(root)


# ADR-O106 (F-078, S-044): the schemas, library and kernel logs refuse an unbumped change after these entries; the
# changes before them that kept their version (36, 21 and 47) stay as written, the logs being append-only.
BUMP_CHECKED_AFTER = {"schemas": 125, "library": 77, "kernel": 55, "docs": 0}


def _freeze_problems(root):
    """Frozen docs (owner O64) and, since ADR-O106, schemas, library cards and kernel files: a log entry that changes a
    file must also change its version."""
    from kernel.schema_log import LOGS

    found = []
    for name, log in LOGS.items():
        last = {}
        for row in log.entries(root):
            previous = last.get(row[log.key])
            if (row["change"] == "changed" and row["seq"] > BUMP_CHECKED_AFTER[name] and previous is not None
                    and previous == row[log.version_key]):
                found.append(f"{log.log} seq {row['seq']}: {row[log.key]} changed without a version bump "
                             f"(still {row[log.version_key]})")
            last[row[log.key]] = row[log.version_key]
    return found


def write(root=ROOT):
    for path, text in generated(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(root))


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--write" in argv:
        write()
        return 0
    found = problems()
    for problem in found:
        print("DOCS", problem)
    print(f"docs plane: {'PASS' if not found else f'{len(found)} problem(s)'}")
    return 1 if found else 0


