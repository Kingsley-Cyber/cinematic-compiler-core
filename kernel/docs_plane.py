def layer_order_text(root=ROOT):
    from kernel.build_docs import step_modules

    order = yaml.safe_load((root / "kernel" / "layer_order.yaml").read_text(encoding="utf-8"))
    modules = step_modules()
    rows = []
    for node in order["nodes"]:
        writes = node["writes"]
        nodes = [w.split("/")[2] for w in writes if w.startswith("/nodes/")]
        edges = [w.split("/")[2] for w in writes if w.startswith("/edges/")]
        other = [w for w in writes if not w.startswith(("/nodes/", "/edges/"))]
        code = modules.get(node["id"])
        code = root / code.relative_to(ROOT) if code else None  # links stay inside the tree being checked
        rows.append([node["step_id"], f"`{node['id']}`", LAYER_LABELS[node["id"]], str(node["band"]),
                     ", ".join(node.get("when", ["all"])) if isinstance(node.get("when"), list) else "all",
                     ", ".join(nodes) or "—", ", ".join(edges) or "—", ", ".join(f"`{o}`" for o in other) or "—",
                     ", ".join(node.get("depends_on", [])) or "—", ", ".join(node.get("validated_by", [])) or "—",
                     f"[{code.name}]({_rel(code, root / 'docs')})" if code else "not built"])
    endpoints = [[f"`{name}`", ", ".join(e["from"]), ", ".join(e["to"])] for name, e in order["edge_endpoints"].items()]
    return "\n".join([
        "# Layer order", "", GENERATED.format(source="kernel/layer_order.yaml"), "",
        f"Layer order version **{order['version']}** (kernel {order['kernel']}, envelope {order['envelope']}). The step "
        "IDs carry the order: a step reads only what the steps before it wrote, and writes only its own paths "
        "(`check_pass_writes`, WRITE_SCOPE). The Layer column is the owner's corrected list (O57, O58); the Band column "
        "is the repo's own grouping.", "",
        "Rules this table enforces: constraints come before beats (S03 before S04); temporal and causal are separate "
        "steps on shared beats; the UGC layers run only for `ugc_ad`; facial runs only for live action and UGC (O57); "
        "camera comes after effort and reads it; render (L6) and post-generation (L6.5) are terminal and have nodes "
        "only, as do intent (L0, a document) and brief (L0.5) (O58). A check goes at the first step that can see its "
        "data (plan v1.2).", "",
        _table(["Step", "Node", "Layer", "Band", "Runs for", "Writes nodes", "Writes edges", "Other paths",
                "Depends on", "Validated by", "Code"], rows), "",
        "## Edge groups", "", _table(["Edge group", "From", "To"], endpoints), "",
        "## Changing the layer order", "",
        "Never by hand. A change needs an accepted ADR (docs/decisions/), then an edit of `kernel/layer_order.yaml`, "
        "its kernel log entry (`python -m kernel.schema_log --log kernel record kernel/layer_order.yaml ...`), the "
        "version bump in the file, and `make docs`. `scripts/verify.sh` refuses the rest.", ""])


def rules_data(root=ROOT):
    return yaml.safe_load((root / "docs" / "rules.yaml").read_text(encoding="utf-8"))


def rules_text(root=ROOT):
    data = rules_data(root)
    parts = ["# Rules", "", GENERATED.format(source="docs/rules.yaml"), "",
             f"Rulebook version **{data['version']}**. One rule per row; every rule cites the decisions it comes from "
             "and names what enforces it (a code or test the gate runs, or `protocol` for a rule the agent follows). "
             "No two rules contradict; a later decision changes a rule only through a new version of this file.", ""]
    for scope, title in (("agent", "How agents work"), ("compiler", "What the compiler guarantees"),
                         ("prompt", "What every prompt must say"), ("owner", "What only the owner does")):
        rows = [[r["id"], _cell(r["rule"]), ", ".join(r["source"]), _cell(", ".join(r["enforced_by"]))]
                for r in data["rules"] if r["scope"] == scope]
        parts += [f"## {title}", "", _table(["Rule", "Statement", "Source", "Enforced by"], rows), ""]
    return "\n".join(parts)


def repo_codes(root=ROOT):
    """Every quoted UPPER_SNAKE code in the compiler's Python (passes, planner, solver, validators, renderers)."""
    found = set()
    for folder in ("compiler", "planner", "solver", "validators", "renderers", "kernel", "kernel_extraction"):
        for path in (root / folder).rglob("*.py"):
            found |= set(re.findall(r"[\"']([A-Z][A-Z0-9]+(?:_[A-Z0-9]+)+)[\"']", path.read_text(encoding="utf-8")))
    return found


def backlog(root=ROOT):
    return yaml.safe_load((root / "docs" / "plans" / "backlog.yaml").read_text(encoding="utf-8"))


def plan_text(root=ROOT):
    data, codes = backlog(root), repo_codes(root)
    findings = {f["id"]: f for f in items("findings", root)}
    rows = []
    for item in data["items"]:
        built = [c for c in item.get("codes", []) if c in codes]
        rows.append([item["id"], _cell(item["title"]), item["status"], item["step"], LAYER_LABELS.get(item["step"], "—")
                     if item["step"] in LAYER_LABELS else item["step"],
                     ", ".join(item.get("findings", [])) or "—",
                     ", ".join(f"{c}{' ✓' if c in built else ''}" for c in item.get("codes", [])) or "—",
                     ", ".join(item.get("depends_on", [])) or "—", item.get("plan", "—")])
    counts = {s: sum(i["status"] == s for i in data["items"]) for s in BACKLOG_STATUS}
    next_items = [i["id"] for i in data["items"] if i["status"] == "next"]
    open_ = [f for f in findings.values() if value(f, "Status") not in CLOSED]
    return "\n".join([
        "# Plan", "", GENERATED.format(source="docs/plans/backlog.yaml, the repo's codes and docs/findings/"), "",
        f"Backlog version **{data['version']}**. The build order across every plan, one row per slice. A code with ✓ "
        "is in the code today (found in the compiler's Python); a slice is `done` only when all its new codes are. "
        "Status counts: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + f". Next: {', '.join(next_items) or 'none'}."
        f" Open findings: {len(open_)} ({sum(value(f, 'Severity') == 'critical' for f in open_)} critical, "
        f"{sum(value(f, 'Severity') == 'high' for f in open_)} high).", "",
        _table(["Slice", "Title", "Status", "Step", "Layer", "Findings", "New codes", "Depends on", "Plan"], rows), "",
        "## Status values", "", ", ".join(f"`{s}`" for s in BACKLOG_STATUS), "",
        "Change a slice's status in `docs/plans/backlog.yaml` (with its commit) and run `make docs`.", ""])


