"""The docs plane (owner O64, O67): the five indexes, the canonical generated docs and their drift checks.

Artifacts are one file each, in five folders: docs/plans, docs/findings, docs/decisions, docs/sessions and
docs/renders, each with a `_template.md`. A file starts `# <ID> — <Title>`; every `## <Field>` section below it holds
that field, and the first paragraph is the field's value (later paragraphs are detail).

Generated here, never edited by hand (`python -m kernel.docs_plane --write`):
- docs/index/{plans,findings,decisions,sessions,renders}.md, one row per artifact file;
- docs/bootstrap/state.md, where the work stands (owner O69);
- docs/layer_order.md from kernel/layer_order.yaml; docs/rules.md from docs/rules.yaml; docs/plan.md from
  docs/plans/backlog.yaml and the codes in the repo;
- the blocks between `<!-- BEGIN GENERATED: <name> -->` and `<!-- END GENERATED: <name> -->` in AGENTS.md
  (layer_order, rules, state, rulings) and docs/for_the_owner.md (rulings).

`--check` (scripts/verify.sh) refuses: an artifact without its required fields or with a value outside its legend, an
ID that disagrees with its file name, a duplicated ID, a relative link to a missing file, a stale generated file or
block, a decision chain that disagrees with itself (supersedes vs superseded by), a rule whose source decision is not
accepted, a backlog item marked done whose new codes are not in the code (or a not-done item whose codes all are), a
backlog dependency or finding that does not exist, and a migrated render finding (F1-F15) whose status disagrees with
the checklist's caught_by codes (validators/checklist.FINDINGS).
"""

