"""The between-keys report (RV-59a; F-159, F-089): every frame of the four examples strictly between an entity's keys,
posed along the declared interpolation (solver/interpolation.py: joints slerped, the root straight), measured the way
S13 measures its keys: two bodies whose capsules overlap (BODY_OVERLAP's measure, no depth allowed) and a body point
more than 0.15 m under the floor (FLOOR_PENETRATION's). S13 checks the keys; between them this report measures, until
RV-59e (the overlaps, after F-220) and RV-59c (the floor) refuse.

    python -m validators.between_keys_report > docs/reports/<date>-between-keys.md
"""

import json

from compiler.examples import EXAMPLES
from planner.dynamic_beat_validator import vanish_windows
from solver import body_overlap, forward_kinematics, interpolation
from solver.floor_penetration import TOLERANCE_M, floor_level
from validators.contact_world_report import REPO_ROOTS, SOURCE


def _keys(envelope):
    keys = {}
    for key in sorted(envelope["nodes"]["motion"]["items"], key=lambda k: (k["t"], k["id"])):
        keys.setdefault(key["entity"], []).append(key)
    return keys


def _span(keys, entity, t):
    """(from, to) of the entity's keys around t."""
    own = keys[entity]
    before = max((k["t"] for k in own if k["t"] < t), default=None)
    after = min((k["t"] for k in own if k["t"] > t), default=None)
    return before, after


def _whose(example, entity, span):
    """'source rows' when both ends are the owner's source rows, else 'repo keys'."""
    own = (example, entity) in SOURCE and not any((example, entity, end) in REPO_ROOTS for end in span)
    return "source rows" if own else "repo keys"


def measure(example):
    """{"frames": n, "sinks": [...], "overlaps": [...]} for one example, each row a span with its deepest frame."""
    envelope = json.loads((EXAMPLES / example / "envelope.json").read_text(encoding="utf-8"))
    genre, fps = envelope["scene"]["genre"], envelope["scene"]["fps"]
    metres, radii = forward_kinematics.segments(genre), forward_kinematics.radii(genre)
    keys = _keys(envelope)
    gone = [(entity, start, back) for entity, _, start, back in vanish_windows(envelope["nodes"]["beats"]["items"])]
    poses = interpolation.frames(keys, fps, gone)
    floor = floor_level(envelope["nodes"]["surfaces"]["items"], envelope["scene"]["ax"].get("ground"))
    sinks = {}
    for (entity, t), pose in sorted(poses.items(), key=lambda item: (item[0][1], item[0][0])):
        part, point = min(forward_kinematics.points(pose, metres).items(), key=lambda item: (item[1][1], item[0]))
        depth = round(floor - point[1], 3) if floor is not None else 0.0
        if depth > TOLERANCE_M:
            span = _span(keys, entity, t)
            row = sinks.setdefault((entity, span), {"entity": entity, "span": span, "frames": 0, "deepest": 0.0,
                                                    "whose": _whose(example, entity, span)})
            row["frames"] += 1
            if depth > row["deepest"]:
                row.update(deepest=depth, at=t, part=part)
    # every body at every frame: a body between keys is posed, one at a key is its key
    at = {}
    for (entity, t), pose in poses.items():
        at.setdefault(t, {})[entity] = pose
    for entity, own in keys.items():
        for key in own:
            at.setdefault(round(key["t"], 6), {}).setdefault(entity, key)
    bodies = {(entity, t): {"id": f"{entity}@{t:g}", "capsules": forward_kinematics.capsules(pose, metres, radii)}
              for t, here in at.items() if len(here) > 1 for entity, pose in here.items()}
    overlaps = {}
    for t, first, second, depth, one, other in body_overlap.overlaps(bodies):
        if all(any(abs(k["t"] - t) < 1e-6 for k in keys[entity]) for entity in (first[0], second[0])):
            continue  # both at their keys: S13's BODY_OVERLAP already judges it
        pair = (first[0], second[0])
        spans = tuple(_span(keys, entity, t) for entity in pair)
        row = overlaps.setdefault((pair, spans), {"pair": pair, "spans": spans, "frames": 0, "deepest": 0.0,
                                                  "whose": [_whose(example, e, s) for e, s in zip(pair, spans, strict=True)]})
        row["frames"] += 1
        if depth > row["deepest"]:
            row.update(deepest=depth, at=t, parts=(one, other))
    return {"frames": len(poses), "sinks": list(sinks.values()), "overlaps": list(overlaps.values())}


def _t(value):
    return "—" if value is None else f"{value:g}"


def markdown(examples=("reference_fight", "wizard_vs_acrobat", "live_action_standoff", "ugc_glasses_demo")):
    lines = ["# Bodies between keys (2026-10-12)", "",
             "Generated by `python -m validators.between_keys_report` (RV-59a; F-159, F-089). Every frame strictly between",
             "an entity's keys at the scene's fps, posed along the declared interpolation (joints slerped, the root straight,",
             "a declared turn's angles straight; solver/interpolation.py), a vanished body left out. An overlap is two bodies'",
             "capsules meeting (BODY_OVERLAP's measure, no depth allowed); a sink is a body point more than 0.15 m under the",
             "floor (FLOOR_PENETRATION's). Whose: 'source rows' when both keys of a span are the owner's (A in the reference",
             "fight), else 'repo keys'.", ""]
    for example in examples:
        found = measure(example)
        lines += [f"## {example}", "", f"{found['frames']} frames between keys; {len(found['overlaps'])} overlapping spans; "
                  f"{len(found['sinks'])} sinking spans.", ""]
        if found["overlaps"]:
            lines += ["| Bodies | Spans | Frames | Deepest (m) | At | Parts | Whose |", "|---|---|---|---|---|---|---|"]
            for row in sorted(found["overlaps"], key=lambda r: r["at"]):
                spans = "; ".join(f"{_t(a)}-{_t(b)}" for a, b in row["spans"])
                lines.append(f"| {' / '.join(row['pair'])} | {spans} | {row['frames']} | {row['deepest']:.3f} | {row['at']:g} | "
                             f"{' / '.join(row['parts'])} | {', '.join(row['whose'])} |")
            lines.append("")
        if found["sinks"]:
            lines += ["| Body | Span | Frames | Deepest (m) | At | Part | Whose |", "|---|---|---|---|---|---|---|"]
            for row in sorted(found["sinks"], key=lambda r: r["at"]):
                lines.append(f"| {row['entity']} | {_t(row['span'][0])}-{_t(row['span'][1])} | {row['frames']} | "
                             f"{row['deepest']:.3f} | {row['at']:g} | {row['part']} | {row['whose']} |")
            lines.append("")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(markdown(), end="")
