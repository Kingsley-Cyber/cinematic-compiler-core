"""The contact-miss report (owner O81): every contact of the four examples measured by solver/contact_world.py,
each miss grouped the owner's four ways, written to docs/reports/ for review before CONTACT_WORLD refuses (M9-06b).

    python -m validators.contact_world_report > docs/reports/<date>-contact-world-misses.md

The likely cause is a heuristic (Claude's, for owner review): a target farther from the actor's pelvis than the limb
can reach (arm: torso to shoulder plus 0.65 m; leg: 0.98 m) is out of reach of the root (the position needs
re-blocking); a nearer one is a pose that does not point the limb at it; a torso or head contact moves the body.
"""

import json
import math

from compiler.examples import EXAMPLES
from solver import contact_world

SOURCE = {("reference_fight", "ninja_lean")}  # the owner's source rows (kernel/sources/lbn-2.3-adv.txt), not rewritten
REPO_ROOTS = {("reference_fight", "ninja_lean", 0.6), ("reference_fight", "ninja_lean", 7.5),  # A's rows whose root the
              ("reference_fight", "ninja_lean", 8.0)}  # repo authored (O21's pillar-top landing, O18's pickups)
REACH = {"hand": 0.65 + 0.5, "arm": 0.5 + 0.3, "foot": 0.98, "leg": 0.55}
NOTES = {("reference_fight", "b19_c2"): "expected: since F-064 (O77) the kunai lands at [0.6, 0, 4.0], about 1.3 m from "
                                       "A's 8.00 crouch (O18's grounded pickup)"}


def _band(distance):
    return "small (<0.3 m)" if distance < 0.3 else "large (>1.0 m)" if distance > 1.0 else "medium (0.3-1.0 m)"


def _cause(row, pelvis):
    limb = row["part"].split("_")[-1]
    reach = REACH.get(limb)
    if row["kind"] == "foot or body on a surface":
        return f"the {row['part'].replace('_', ' ')} sits off the surface: root height or pose"
    if limb in ("torso", "head"):
        return "the body sits off the target: move the root or bend the spine"
    if reach is not None and math.dist(pelvis, row["target_point"]) > reach:
        return "out of the root's reach: re-block the position"
    return "the pose does not point the limb at it: re-pose the limb"


def rows():
    out = []
    for name in sorted(p.name for p in EXAMPLES.iterdir() if (p / "request.json").exists()):
        envelope = json.loads((EXAMPLES / name / "envelope.json").read_text(encoding="utf-8"))
        labels = envelope["nodes"]["render"]["items"][0]["labels"]
        pelvis = {(k["entity"], round(k["t"], 6)): k["pos"] for k in envelope["nodes"]["motion"]["items"]}
        for row in contact_world.measure(envelope):
            row = {**row, "example": name, "label": labels.get(row["actor"], row["actor"]),
                   "source": "source A row" if (name, row["actor"]) in SOURCE
                   and (name, row["actor"], round(row["t"], 6)) not in REPO_ROOTS else "repo-authored key"}
            if row["measurable"]:
                row["cause"] = NOTES.get((name, row["id"])) or _cause(row, pelvis[(row["actor"], round(row["t"], 6))])
            out.append(row)
    return out


def _flags(row):
    flags = [name for name, on in (("airborne", row["airborne"]), ("rotating", row["rotating"]),
                                   ("prop moving", row["prop_moving"])) if on]
    return ", ".join(flags) or "—"


HEAD = "Example | Contact | t | Who | Part -> target"


def _cells(row):
    part = row["part"].replace("_", " ")
    return f"{row['example']} | {row['id']} | {row['t']:.2f} | {row['label']} | {part} -> {row['target']}"


def _real(row):
    return "real" if _flags(row) == "—" else f"artefact ({_flags(row)})"


def markdown(all_rows):
    measured = [r for r in all_rows if r["measurable"]]
    misses = sorted((r for r in measured if r["distance"] > contact_world.TOLERANCE_M), key=lambda r: -r["distance"])
    lines = ["# Contact misses by forward kinematics, hips read from the trunk (2026-10-11)", "",
             "Generated by `python -m validators.contact_world_report` (backlog M9-06c; owners O81, O82, O84, O85) with the",
             "hips read from the trunk and the anime body's leg fitted to the source's grounded A rows; the repo-authored",
             "roots stand at the pelvis (ADR-O72). Segment lengths: library/body_segments.yaml (draft; an anime and an adult",
             "body). A miss is a distance over 0.15 m between the actor's point and the target's at the contact's instant.",
             "A's rows at 0.6, 7.5 and 8.0 count as repo-authored (their roots are the repo's: O21, O18). Likely causes are",
             "a heuristic (validators/contact_world_report.py).", "",
             f"Measured {len(measured)} contacts: {len(measured) - len(misses)} within 0.15 m, {len(misses)} misses; "
             f"{len(all_rows) - len(measured)} not measurable.", ""]
    def count(key):
        out = {}
        for r in misses:
            out[key(r)] = out.get(key(r), 0) + 1
        return ", ".join(f"{k}: {v}" for k, v in sorted(out.items()))
    lines += ["## Misses by group", "",
              f"- Whose pose: {count(lambda r: r['source'])}",
              f"- Kind: {count(lambda r: r['kind'])}",
              f"- Size: {count(lambda r: _band(r['distance']))}",
              f"- Real or measurement artefact: {count(_real)}",
              "", "## Every miss", "",
              f"| {HEAD} | Miss (m) | Whose pose | Kind | Size | Artefact flags | Likely cause |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    lines += [f"| {_cells(r)} | {r['distance']:.2f} | {r['source']} | {r['kind']} | {_band(r['distance'])} | {_flags(r)} | "
              f"{r['cause']} |" for r in misses]
    lines += ["", "## Within 0.15 m", "", f"| {HEAD} | Miss (m) |", "|---|---|---|---|---|---|"]
    lines += [f"| {_cells(r)} | {r['distance']:.2f} |" for r in measured if r["distance"] <= contact_world.TOLERANCE_M]
    lines += ["", "## Not measurable", "", f"| {HEAD} | Why |", "|---|---|---|---|---|---|"]
    lines += [f"| {_cells(r)} | {r['reason']} |" for r in all_rows if not r["measurable"]]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(markdown(rows()), end="")
